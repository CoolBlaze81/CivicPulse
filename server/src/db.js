// ---- placeholders ------------------------------------------------------

const converted = new Map();
// `?` -> `$1, $2 ...`, leaving quoted text alone.
function toPg(sql) {
  let out = converted.get(sql);
  if (out) return out;
  let n = 0;
  let quote = null;
  out = '';
  for (const ch of sql) {
    if (quote) {
      if (ch === quote) quote = null;
      out += ch;
    } else if (ch === "'" || ch === '"') {
      quote = ch;
      out += ch;
    } else if (ch === '?') {
      n += 1;
      out += `$${n}`;
    } else out += ch;
  }
  converted.set(sql, out);
  return out;
}

// undefined and NaN become NULL (SQLite used to accept them silently).
const clean = (params) => params.map((p) => (p === undefined || (typeof p === 'number' && !Number.isFinite(p)) ? null : p));

