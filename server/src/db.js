// A connection is { query(text, params) -> {rows, rowCount}, exec(sql), transaction(fn), close() }.

async function pgliteConnection(dataDir) {
  const { PGlite } = await import('@electric-sql/pglite');
  if (dataDir) fs.mkdirSync(dataDir, { recursive: true });
  const db = await PGlite.create(dataDir || undefined, { parsers: { 1700: Number, 20: Number } });
  const wrap = (q) => ({
    async query(text, params) {
      const r = await q.query(text, params);
      return { rows: r.rows, rowCount: r.affectedRows ?? r.rows.length };
    },
    exec: (sql) => q.exec(sql),
  });
  return {
    kind: 'pglite',
    ...wrap(db),
    transaction: (fn) => db.transaction((t) => fn(wrap(t))),
    close: () => db.close(),
  };
}

async function pgConnection(url) {
  const { default: pg } = await import('pg');
  pg.types.setTypeParser(1700, Number);
  pg.types.setTypeParser(20, Number);
  const local = /localhost|127\.0\.0\.1/.test(url);
  const pool = new pg.Pool({
    connectionString: url,
    max: Number(process.env.PG_POOL_MAX || 5),
    ssl: local ? undefined : { rejectUnauthorized: false },
  });
  const wrap = (c) => ({
    query: (text, params) => c.query(text, params),
    exec: (sql) => c.query(sql),
  });
  return {
    kind: 'pg',
    ...wrap(pool),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const out = await fn(wrap(client));
        await client.query('COMMIT');
        return out;
      } catch (e) {
        await client.query('ROLLBACK').catch(() => {});
        throw e;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

// target: ':memory:' | a directory for PGlite | a postgres:// URL.
export async function connect(target) {
  const conn = /^postgres(ql)?:\/\//.test(target || '')
    ? await pgConnection(target)
    : await pgliteConnection(target === ':memory:' ? null : target);
  await conn.exec(SCHEMA);
  return conn;
}

let root = null;
let opening = null;
const scope = new AsyncLocalStorage(); // { conn, inTx }

export function defaultTarget() {
  return process.env.DATABASE_URL || process.env.CIVICPULSE_DB || path.join(DATA_DIR, 'pglite');
}

export async function openDb(target = defaultTarget()) {
  if (root) await root.close().catch(() => {});
  root = null;
  opening = connect(target).then((c) => {
    root = c;
    return c;
  });
  return opening;
}

export async function ready() {
  if (root) return root;
  if (!opening) openDb();
  return opening;
}

function current() {
  const c = scope.getStore()?.conn || root;
  if (!c) throw new Error('Database not open. Call openDb() or await ready() first.');
  return c;
}

async function query(sql, params) {
  return current().query(toPg(sql), clean(params));
}

const statement = (sql) => ({
  async get(...params) {
    return (await query(sql, params)).rows[0];
  },
  async all(...params) {
    return (await query(sql, params)).rows;
  },
  // INSERTs return the new row's id as lastInsertRowid.
  async run(...params) {
    const insert = /^\s*INSERT\s/i.test(sql) && !/\bRETURNING\b/i.test(sql);
    const r = await query(insert ? `${sql} RETURNING *` : sql, params);
    return {
      changes: r.rowCount,
      lastInsertRowid: insert && r.rows[0] ? Object.values(r.rows[0])[0] : undefined,
    };
  },
});

const facade = {
  prepare: statement,
  exec: (sql) => current().exec(sql),
  get kind() {
    return current().kind;
  },
};

export function getDb() {
  return facade;
}

// Runs fn inside one transaction; nested calls join the outer one.
export function tx(fn) {
  const store = scope.getStore();
  if (store?.inTx) return fn();
  const base = store?.conn || current();
  return base.transaction((conn) => scope.run({ conn, inTx: true }, fn));
}

// Runs fn with every query going to another connection (used to build the
// demo data in memory before copying it to a remote database).
export function withConnection(conn, fn) {
  return scope.run({ conn, inTx: false }, fn);
}

export function nowIso(date = new Date()) {
  return date.toISOString();
}
